function updateReadme(roleKey, spec, rel) {
  const absolute = path.join(ROOT, rel.readme);
  const text = fs.readFileSync(absolute, "utf8");
  const block = lines([
    README_START,
    "",
    `## ${spec.title}`,
    "",
    `- 구분: ${spec.status}`,
    `- [단계별 상세 실습팩](${BASE_URL}${rel.markdown})`,
    `- [브라우저 결과 구조 예시](${BASE_URL}${rel.html})`,
    `- ${spec.timeRule}`,
    "",
    README_END,
  ]);
  const pattern = new RegExp(README_START + "[\\s\\S]*?" + README_END, "g");
  const next = pattern.test(text) ? text.replace(pattern, block) : text.trimEnd() + "\n\n" + block + "\n";
  fs.writeFileSync(absolute, next, "utf8");
}

